CREATE TABLE IF NOT EXISTS stores (
  store_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  address TEXT,
  locality TEXT,
  city TEXT,
  state TEXT,
  postal_code TEXT,
  latitude DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
  geographic_source_id TEXT UNIQUE,
  location_source TEXT,
  geography_retrieved_at TIMESTAMPTZ,
  store_type TEXT NOT NULL DEFAULT 'unknown',
  verification_status TEXT NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('verified', 'unverified', 'simulated')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS stores_city_locality_idx ON stores (city, locality);
CREATE INDEX IF NOT EXISTS stores_location_idx ON stores (latitude, longitude)
  WHERE latitude IS NOT NULL AND longitude IS NOT NULL;

CREATE TABLE IF NOT EXISTS products (
  sku TEXT PRIMARY KEY,
  product_name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'other',
  size TEXT,
  selling_price NUMERIC(12, 2) CHECK (selling_price IS NULL OR selling_price >= 0),
  unit_cost NUMERIC(12, 2) CHECK (unit_cost IS NULL OR unit_cost >= 0),
  unit_margin NUMERIC(12, 2),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS inventory (
  store_id BIGINT NOT NULL REFERENCES stores(store_id),
  sku TEXT NOT NULL REFERENCES products(sku),
  current_stock INTEGER NOT NULL CHECK (current_stock >= 0),
  safety_stock INTEGER CHECK (safety_stock IS NULL OR safety_stock >= 0),
  shelf_capacity INTEGER NOT NULL CHECK (shelf_capacity >= current_stock),
  baseline_hourly_demand NUMERIC(12, 3) NOT NULL DEFAULT 0
    CHECK (baseline_hourly_demand >= 0),
  transfer_eta_hours NUMERIC(8, 3) CHECK (transfer_eta_hours IS NULL OR transfer_eta_hours >= 0),
  transport_capacity INTEGER CHECK (transport_capacity IS NULL OR transport_capacity >= 0),
  earlier_truck_available BOOLEAN,
  earlier_truck_arrival_hour NUMERIC(8, 3)
    CHECK (earlier_truck_arrival_hour IS NULL OR earlier_truck_arrival_hour >= 0),
  earlier_truck_units INTEGER CHECK (earlier_truck_units IS NULL OR earlier_truck_units >= 0),
  shelf_space_shareable BOOLEAN,
  inventory_source TEXT NOT NULL DEFAULT 'demo seed',
  verification_status TEXT NOT NULL DEFAULT 'simulated'
    CHECK (verification_status IN ('verified', 'unverified', 'simulated')),
  last_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (store_id, sku)
);

CREATE TABLE IF NOT EXISTS hourly_sales (
  record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(store_id),
  sku TEXT NOT NULL REFERENCES products(sku),
  hour_start TIMESTAMPTZ NOT NULL,
  quantity_sold INTEGER NOT NULL CHECK (quantity_sold >= 0),
  data_source TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (store_id, sku, hour_start, data_source)
);

CREATE INDEX IF NOT EXISTS hourly_sales_forecast_idx
  ON hourly_sales (store_id, sku, hour_start DESC);

CREATE TABLE IF NOT EXISTS warehouse_inventory (
  warehouse_id TEXT NOT NULL,
  sku TEXT NOT NULL REFERENCES products(sku),
  available_stock INTEGER NOT NULL CHECK (available_stock >= 0),
  last_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  data_source TEXT NOT NULL,
  PRIMARY KEY (warehouse_id, sku)
);

CREATE TABLE IF NOT EXISTS trucks (
  truck_id TEXT PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(store_id),
  scheduled_arrival_at TIMESTAMPTZ NOT NULL,
  truck_capacity INTEGER CHECK (truck_capacity IS NULL OR truck_capacity >= 0),
  reserved_capacity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_capacity >= 0),
  delivery_status TEXT NOT NULL DEFAULT 'scheduled'
    CHECK (delivery_status IN ('scheduled', 'in_transit', 'delivered', 'cancelled')),
  data_source TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS truck_deliveries (
  truck_id TEXT NOT NULL REFERENCES trucks(truck_id) ON DELETE CASCADE,
  sku TEXT NOT NULL REFERENCES products(sku),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (truck_id, sku)
);

CREATE TABLE IF NOT EXISTS events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name TEXT NOT NULL,
  event_type TEXT NOT NULL,
  location TEXT,
  latitude DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL CHECK (ends_at > starts_at),
  affected_category TEXT NOT NULL,
  expected_demand_uplift_percent NUMERIC(8, 3) NOT NULL
    CHECK (expected_demand_uplift_percent >= 0),
  uplift_source TEXT NOT NULL,
  verification_status TEXT NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('verified', 'unverified', 'simulated')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS events_time_category_idx
  ON events (starts_at, ends_at, affected_category);

CREATE TABLE IF NOT EXISTS riders (
  availability_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(store_id),
  available_at TIMESTAMPTZ NOT NULL,
  available_rider_count INTEGER NOT NULL CHECK (available_rider_count >= 0),
  orders_per_rider_per_hour NUMERIC(8, 3) NOT NULL
    CHECK (orders_per_rider_per_hour >= 0),
  data_source TEXT NOT NULL,
  UNIQUE (store_id, available_at, data_source)
);

CREATE TABLE IF NOT EXISTS actions (
  action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_type TEXT NOT NULL,
  sku TEXT NOT NULL REFERENCES products(sku),
  quantity INTEGER NOT NULL CHECK (quantity >= 0),
  source_store_id BIGINT REFERENCES stores(store_id),
  destination_store_id BIGINT REFERENCES stores(store_id),
  status TEXT NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  feasible BOOLEAN NOT NULL DEFAULT FALSE,
  required_quantity INTEGER NOT NULL DEFAULT 0 CHECK (required_quantity >= 0),
  estimated_unfilled_units_after_action INTEGER NOT NULL DEFAULT 0
    CHECK (estimated_unfilled_units_after_action >= 0),
  estimated_impact JSONB NOT NULL DEFAULT '{}'::JSONB,
  explanation TEXT NOT NULL,
  constraints JSONB NOT NULL DEFAULT '[]'::JSONB,
  scenario TEXT NOT NULL DEFAULT 'baseline',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  approval_at TIMESTAMPTZ,
  rejection_at TIMESTAMPTZ,
  manager_decision TEXT
);

CREATE INDEX IF NOT EXISTS actions_status_created_idx ON actions (status, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS actions_pending_scenario_idx
  ON actions (destination_store_id, sku, scenario)
  WHERE status = 'PENDING' AND action_type IN ('TRANSFER', 'REVIEW');

CREATE TABLE IF NOT EXISTS demo_deliveries (
  delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores(store_id),
  sku TEXT NOT NULL REFERENCES products(sku),
  arrival_hour INTEGER NOT NULL CHECK (arrival_hour BETWEEN 1 AND 24),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  data_source TEXT NOT NULL DEFAULT 'simulated action'
);
