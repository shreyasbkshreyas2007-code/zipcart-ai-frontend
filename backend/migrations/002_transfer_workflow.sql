ALTER TABLE actions ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS shelf_slot TEXT;

ALTER TABLE actions DROP CONSTRAINT IF EXISTS actions_status_check;
ALTER TABLE actions
  ADD CONSTRAINT actions_status_check
  CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'COMPLETED'));

CREATE TABLE IF NOT EXISTS action_history (
  history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_id BIGINT NOT NULL REFERENCES actions(action_id) ON DELETE CASCADE,
  from_status TEXT,
  to_status TEXT NOT NULL
    CHECK (to_status IN ('PENDING', 'APPROVED', 'REJECTED', 'COMPLETED')),
  details JSONB NOT NULL DEFAULT '{}'::JSONB,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS action_history_action_idx
  ON action_history (action_id, occurred_at DESC);
